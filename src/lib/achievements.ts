/** Rarity for visual treatment — matches page mapping. */
export type Rarity = "common" | "rare" | "epic" | "legendary";

/**
 * Data-driven achievement definition.
 * Pure: all fields are serializable; no React components here.
 * `unlocked` and `progress` are computed from progress input.
 */
export interface AchievementDef {
  id: string;
  title: string;
  description: string;
  xp: number;
  rarity: Rarity;
  /** Lucide icon key — page maps string -> component. */
  icon: string;
  unlocked: boolean;
  /** 0..1 — min(current/target, 1) */
  progress: number;
  current: number;
  target: number;
}

export interface AchievementProgress extends UserProgress {
  /** Optional certificate tracks the learner has earned (e.g. ["c","python"]) */
  certificates?: string[];
}

type Blueprint = {
  id: string;
  title: string;
  description: string;
  xp: number;
  rarity: Rarity;
  icon: string;
  target: number;
  current: (p: AchievementProgress, total: number) => number;
  unlocked: (p: AchievementProgress, total: number) => boolean;
};

function clamp01(n: number): number {
  if (!Number.isFinite(n)) return 0;
  return Math.max(0, Math.min(1, n));
}

function toBlueprints(input: Blueprint[]): Blueprint[] {
  return input;
}

// Shared helpers — pure, testable
function hasDay(p: AchievementProgress, day: number): boolean {
  return p.completedDays.includes(day);
}
function reachedDay(p: AchievementProgress, day: number): boolean {
  return p.completedDays.some((d) => d >= day);
}
function countDays(p: AchievementProgress): number {
  return p.completedDays.length;
}
function notesCount(p: AchievementProgress): number {
  return Object.keys(p.notes ?? {}).filter((k) => {
    const v = (p.notes as Record<string, string>)[k];
    return typeof v === "string" && v.trim().length > 0;
  }).length;
}
function assignmentsCount(p: AchievementProgress): number {
  return (p.completedAssignments ?? []).length;
}

