/**
 * Build achievements for a track from live progress.
 * Pure — no I/O, no React. Returns every achievement with `unlocked` and `progress` (0..1).
 */
export function buildAchievements(
  track: TrackKey,
  progress: AchievementProgress
): AchievementDef[] {
  const total = TOTAL_TRACKS[track] ?? 0;
  const list = BLUEPRINTS[track] ?? [];
  return list.map((b) => {
    const cur = b.current(progress, total);
    const unl = b.unlocked(progress, total);
    const prog = b.target > 0 ? clamp01(cur / b.target) : unl ? 1 : 0;
    return {
      id: b.id,
      title: b.title,
      description: b.description,
      xp: b.xp,
      rarity: b.rarity,
      icon: b.icon,
      unlocked: unl,
      progress: prog,
      current: cur,
      target: b.target,
    };
  });
}

